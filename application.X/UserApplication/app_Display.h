#define FADEM       0x02        //##(0)渐变显示模式
#define CHASERM     0x03        //##(0)跑马灯显示模式    
#define BLINKM      0x04        //##(0)闪烁显示模式 
/*###############################################################################################################################
# LED变量声明                                                                                                                   #
# 动画类型                                                                                                                      #
# 0x01 – 静态（STATIC）                                                                                                        #
          使用 HSL 色彩模式呈现固定颜色 。                                                                                      #
# 0x02 – 渐变（FADE）                                                                                                          #
          在两种 HSL 颜色之间随时间渐变，可选择是否循环 。对于循环渐变动画，需实现 “呼吸灯” 效果：颜色在两种 HSL 值之间先渐入 #
          再渐出，循环往复。                                                                                                    #
# 0x03 – 追逐（CHASER）                                                                                                        #
          按序列点亮 LED，采用 HSL 色彩模式并为每个 LED 设置相位偏移。相位偏移定义了相邻 LED 点亮的延迟时间，每个 LED 会从起始  #
          HSL 颜色渐变至终止 HSL 颜色。                                                                                         #
# 0x04 – 闪烁（BLINK）                                                                                                         #                                     
          在两种 HSL 颜色之间渐变，短暂保持目标颜色后反向渐变，最终回到初始颜色并短暂停留。                                     #
 ##############################################################################################################################*/
#define AnimQy	 30                 //##(0)动画组数量
typedef struct{
    uint8_t mode;                   //##(0)显示模式【静态(STATIC)/渐变(FADE)/追逐(CHASER)/闪烁(BLINK)】
    uint8_t LEDS;                   //##(0)LED 位图,最高位对应"LED0"
    uint8_t StartH;                 //##(0)起始色相    （0-360度对应不同颜色）
    uint8_t StartS;                 //##(0)起始饱和度  （0%-100%）
    uint8_t StartL;                 //##(0)起始亮度    （0%-100%）
    uint8_t EndingH;                //##(0)结束色相    （0-360度对应不同颜色）
    uint8_t EndingS;                //##(0)结束饱和度  （0%-100%）
    uint8_t EndingL;                //##(0)结束亮度    （0%-100%）
   uint16_t Duration;               //##(0)显示持续时间（单位:毫秒）
    uint8_t RepeatCount;            //##(0)显示重复计数,此值为"0"则死循环 
    uint8_t NextInChain;            //##(0)显示链中的下一帧 
   uint16_t Parameter1;             //##(0)动画类型特定参数1,如果显示模式是追逐（CHASER）显示,此值为LED点亮间隔时间(表示多个灯组之间的启动错开程度)
   uint16_t Parameter2;             //##(0)动画类型特定参数2,如果显示模式是追逐（CHASER）显示,此值为"0"则LED0->LED8依次顺序             
}Animation;                         //##(0)每帧动画声明(一个动画有5帧)

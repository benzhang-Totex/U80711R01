/*###############################################################################################################################
# 函数名  :  uint32_t reverse24(uint32_t color)                                                                                 #
# 功  能  :  把 24bit 颜色（BGR）的每个字节，内部位反转                                                                         #
# 参  数  :  NONE                                                                                                               #
# 说  明  :  NONE                                                                                                               #
###############################################################################################################################*/
uint32_t reverse24(uint32_t color) {
   
    uint8_t b = (color >> 16) & 0xFF;               //##(0)取出最高字节"BLUE" (bit16~bit23) 
    uint8_t g = (color >> 8)  & 0xFF;               //##(0)取出中间字节"GREEN"(bit8~bit15) 
    uint8_t r = (color & 0xFF);                     //##(0)取出最低字节"RED"  (bit0~bit7)   
//##(0)对 B 字节做同样位反转
    b = ((b >> 1) & 0x55) | ((b << 1) & 0xAA);      //##(0)交换相邻 1 位：bit0 ↔ bit1，bit2 ↔ bit3...
    b = ((b >> 2) & 0x33) | ((b << 2) & 0xCC);
    b = ((b >> 4) & 0x0F) | ((b << 4) & 0xF0);
 //##(0)对 R 字节做同样位反转
    r = ((r >> 1) & 0x55) | ((r << 1) & 0xAA);      //##(0)交换相邻 4 位：bit0-3  bit4-7
    r = ((r >> 2) & 0x33) | ((r << 2) & 0xCC);
    r = ((r >> 4) & 0x0F) | ((r << 4) & 0xF0);  
//##(0)对 G 字节做同样位反转    
    g = ((g >> 1) & 0x55) | ((g << 1) & 0xAA);      //##(0)交换相邻 2 位：bit0-1  bit2-3...
    g = ((g >> 2) & 0x33) | ((g << 2) & 0xCC);
    g = ((g >> 4) & 0x0F) | ((g << 4) & 0xF0);

//##(0)把反转后的 B、G、R 重新拼成 24bit
    return ((uint32_t)b << 16) | ((uint32_t)g << 8) | r;
}
/*###############################################################################################################################
# 函数名  :  void write_E263HEGBK(uint32_t colorData)                                                                           #
# 功  能  :  向 E263HEGBK 驱动芯片发送 24bit 颜色数据                                                                           #
# 参  数  :  NONE                                                                                                               #
# 说  明  :  NONE                                                                                                               #
###############################################################################################################################*/
void write_E263HEGBK(uint32_t colorData) {
    uint8_t txh_time, txl_time;                     //##(0)高电平/低电平时间,数据 
    uint8_t bits;                                   //##(0)字节/数据位
//##(0)对 24bit 颜色做【位反转】（由于硬件问题造成必须要)         
    colorData = reverse24(colorData);
//##(0)连续发送24位数据到驱动器芯片中
    for(bits=0; bits<24; bits++) {                  //##(0)连续写入24位颜色数据,顺序 B->G->R 
        if(!bit_test(colorData,bits)) {             //##(0)判断数据当前循环位是"0"或者"1"?       
            txh_time = T0H;                         //##(0)发送"0"高电平延时时间
            txl_time = T0L;                         //##(0)发送"0"低电平延时时间
        }else{
            txh_time = T1H;                         //##(0)发送"1"高电平延时时间
            txl_time = T1L;                         //##(0)发送"1"低电平延时时间
        }
        PUST_1;                                     //##(2)发送一个bit时序
        delay_cycles(txh_time);                     //##(3)高电平延时
        PUST_0; 
        delay_cycles(txl_time);                     //##(4)低电平延时  
    }
}

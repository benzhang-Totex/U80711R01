/*###############################################################################################################################
 * @brief HSL转RGBA核心函数,耗时 = 最长(320us) 最短(2us)                                                                        #
 * @param h 色相 (0-360)                                                                                                        #
 * @param s 饱和度 (0-100，百分比)                                                                                              #
 * @param l 亮度 (0-100，百分比)                                                                                                #
 * @param a 透明度 (0-255，直接传入RGBA的Alpha通道)                                                                             #
 * @return 转换后的RGBA颜色结构体，PIC24FJ128GL305 32MHz 需要1.5ms+ 执行时间                                                    #
###############################################################################################################################*/
color HSL_TO_RGBA(uint16_t H, uint8_t S, uint8_t L, uint8_t A) { 
    color rgba;
//##(0)直接赋值透明度  
    rgba.a = A;  
//##(1)处理特殊情况：亮度为0（全黑）或100（全白）
    if(L == 0)   { rgba.r = 0;   rgba.g = 0;   rgba.b = 0;   return rgba;}  //##(0)亮度为"0"返回 RGB = 0  (黑色/关闭)
    if(L == 100) { rgba.r = 255; rgba.g = 255; rgba.b = 255; return rgba;}  //##(0)亮度为"0"返回 RGB = 255(白色/开启)
//##(2)归一化处理：将百分比转为0.0-1.0的浮点值（精简浮点运算）
    float s_norm = (float)S * 0.01f;
    float l_norm = (float)L * 0.01f;
//##(3)计算HSL转RGB的核心参数
    float c = (1.0f - fabs(2.0f * l_norm - 1.0f)) * s_norm;     //##(0)色度
//##(0)色相计算
    //float h_norm = (float)H * HueOffset * (6.0f / 255.0f);      //##(0)H数值为(0 - 255) 色相归一化到 0°- 360°色相
     float h_norm = (float)(H % 360) * 0.0166667f;                       //##(0)H数值为(0 - 360) 色相归一化到 0°- 360°色相
    float x = c * (1.0f - fabs(fmod(h_norm, 2.0f) - 1.0f));     //##(0)辅助参数
    float r_temp = 0.0f, g_temp = 0.0f, b_temp = 0.0f;          //##(0)初始化 "RGB"暂存数值
//##(4)根据色相区间分配临时值
    if (h_norm >= 0 && h_norm < 1) {
        r_temp = c;
        g_temp = x;
        b_temp = 0;
    } else if (h_norm >= 1 && h_norm < 2) {
        r_temp = x;
        g_temp = c;
        b_temp = 0;
    } else if (h_norm >= 2 && h_norm < 3) {
        r_temp = 0;
        g_temp = c;
        b_temp = x;
    } else if (h_norm >= 3 && h_norm < 4) {
        r_temp = 0;
        g_temp = x;
        b_temp = c;
    } else if (h_norm >= 4 && h_norm < 5) {
        r_temp = x;
        g_temp = 0;
        b_temp = c;
    } else if (h_norm >= 5 && h_norm < 6) {
        r_temp = c;
        g_temp = 0;
        b_temp = x;
    }
//##(0)亮度偏移量
    float m = l_norm - c * 0.5f;
//##(0)转换为8位RGB值（0-255）并四舍五入
    rgba.r = (uint8_t)((r_temp + m) * 255.0f + 0.5f);
    rgba.g = (uint8_t)((g_temp + m) * 255.0f + 0.5f);
    rgba.b = (uint8_t)((b_temp + m) * 255.0f + 0.5f);
//##(0)返回RGB
    return (rgba);
}

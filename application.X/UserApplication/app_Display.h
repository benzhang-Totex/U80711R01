/*###############################################################################################################################
# 函数名 :  bool ChaserMode(uint8_t LEDS, colorHSL Start, colorHSL End, uint16_t Duration, bool direction, uint16_t Parameter1) #
# 功  能 :  "LED"追逐显示模式(跑马灯模式)带渐变过渡                                                                             #
# 参  数 :    LEDS = 需要显示的"LED"位图 ,                                                                                      #     
#            Start = 初始显示颜色  , End : 需要显示的颜色 ， Duration = 显示当前"LED"保持时间 ,                                 #
#            Parameter1 = 如果显示模式是追逐（CHASER）显示,此值为LED点亮间隔时间(表示多个灯组之间的启动错开程度)                #    
# 说  明 :  显示完成则返回"1",否则返回"0"                                                                                       #
###############################################################################################################################*/
bool ChaserMode(Animation *Anim) {
    static uint16_t timeout;                    //##(0)时间戳，保存每个阶段起始的system5ms计时值，用于延时判断
    static uint16_t FadeStep;                   //##(0)当前渐变帧步进，记录渐变走到第几帧
    static  int8_t  FadeRng;                    //##(0)渐变范围(淡入淡出) 
    static boolean  FadeForward;                //##(0)渐变方向标志：true暗→亮；false亮→暗
    static boolean  ChaserForward;              //##(0)追逐方向
    static colorHSL COL;                        //##(0)颜色值缓存
    static uint8_t  LEDINX;                     //##(0)显示LED的索引, 正向跑马：LED0→LED7/反向跑马：LED7→LED0
    static uint16_t FRAMES = 0u;                //##(0)单向渐变总帧数，由渐变时长Duration计算得出
              color rgb;                        //##(0)临时缓存HSL转换后的RGB颜色
    static  uint8_t Repeat;                     //##(0)循环次数计数器
           uint32_t ratio;                      //##(0)比例,进度系数
            boolean status = false;             //##(0)函数返回标记，false=动画进行中；true=全部闪烁完成
    static uint16_t Parameter1;                 //##(0)相位偏移延时时间(每个LED显示间隔时间)
//##(0)其它模式状态机复位               
    SM_StateMachine = FM_StateMachine = BM_StateMachine = 0u;
//##(0)执行动画主状态机
    switch(CM_StateMachine) {
//##(0)状态0:动画初始化入口,首次启动/一轮全部跑完都会进这里重置参数
        case 0x00:
             Repeat = 0U;                                           //##(0)渐变步进计数器清零
             CM_StateMachine = 0x01;                    
             break;
        case 0x01:  
             FadeStep = 0U;                                         //##(0)渐变步进计数器清零
             Parameter1 = SWAP_U16(Anim->Parameter1)/5U;            //##(0) 
             ChaserForward = (Anim->Parameter2>>8 == 0U)? 0:1;      //##(0)跑马方向
             LEDINX = (ChaserForward==false)? 0x07 : 0x00;          //##(0)跑马方向【 0x00 :正向LED0→LED7，0x07:反向 LED7→LED0】
             FRAMES = SWAP_U16(Anim->Duration)/5U;                  //##(0)渐变时长转换为渐变所需帧数(5毫秒播放一帧)
             FRAMES = (FRAMES == 0U)? 1U : FRAMES;                  //##(0)防除零
             FadeRng = abs((int16_t)Anim->StartL-Anim->EndingL);    //##(0)计算出渐变跨度范围 
             if(FadeRng>100) { status = true; break; }              //##(0)如果范围超过100则认为是溢出直接返回
             if(Anim->StartL > Anim->EndingL) {                     //##(0)判断起始/结束亮度来决定渐变方向
                COL.H = Anim->StartH;                           
                COL.S = Anim->StartS;                               //##(0)色度/饱和度/亮度为亮度最大的色值                    
                FadeForward = TRUE;                                 //##(0)反向调节 : 亮→暗
             }else{                                              
                COL.H = Anim->EndingH;                          
                COL.S = Anim->EndingS;                              //##(0)色度/饱和度为亮度最大的色值              
                FadeForward = FALSE;                                //##(0)正向调节 : 暗→亮
             }
             timeout = regs.system5ms;                              //##(0)记录当前系统计时，作为下一阶段延时起点
             CM_StateMachine = 0x02;                                //##(0)指向下一步   
             break;
//##(0)状态1:执行 LED跑马灯动画 
        case 0x02:
             if(bit_test(Anim->LEDS,LEDINX)) {                       //##(1)当前LED无需渲染颜色则返回                       
                ratio = ((uint32_t)FadeStep*1000U)/FRAMES;           //##(1)仅亮度"L"渐变,H/S/A固定Start不变
                ratio = FadeRng * ratio / 1000U;                     //##(1)计算出调节量步进的渐变亮度值 
               (FadeForward==false)?
               (COL.L = Anim->StartL + ratio):                       //##(1)暗→亮；递增
               (COL.L = Anim->StartL - ratio);                       //##(1)亮→暗；递减 
                rgb = HSL_TO_RGBA(COL.H, COL.S, COL.L, COL.A);       //##(1)转换成可驱动三基色LED显示的RGB数据
                LEDBUFF[LEDINX] = rgb; 
                DisplayFrameRGB((uint32_t *)LEDBUFF);                //##(1)将LED缓冲区数据输出到硬件,点亮LED
                if(FadeStep++ < FRAMES) break;                       //##(1)渐变没有完成则返回接着渐变
                FadeStep =0U;                                        //##(1)渐变完成则将渐变步进清零
             }
             timeout = regs.system5ms;                              //##(1)记录当前系统计时，作为下一阶段延时起点
             CM_StateMachine = 0x03;                                //##(1)转入相位偏移延时
             break;   
//##(0)状态2: 执行相位偏移延时
        case 0x03:
             if(bit_test(Anim->LEDS,LEDINX)) {                      //##(2)如果当前"LED"无需渲染则无需延时
                if(regs.system5ms-timeout<Parameter1) break;        //##(2)相位偏移延时时间没到则接着延时
                timeout = regs.system5ms;  
             }
             if(ChaserForward == false) {
                if(LEDINX-- >0U) {CM_StateMachine = 2U; break;}     //##(2)反向追逐显示完成  
             }else{
                if(++LEDINX <8U) {CM_StateMachine = 2U; break;}     //##(2)正向追逐显示完成                
             }  
             if(Anim->RepeatCount>0) {                              //##(3)不是循环追逐显示
                if(++Repeat < Anim->RepeatCount) {
                    CM_StateMachine = 1U;                           //##(3)循环次数没有达到则继续追逐显示                       
                }else{
                    status = true;                                  //##(3)追逐显示次数达到则为本帧动画显示完成
                    copyRegisters(FrameRGB,LEDBUFF);                //##(3)保存最后一帧动画  
                    CM_StateMachine = 0U;                           //##(3)追逐动画显示结束
                } 
             }else{
                CM_StateMachine = 1U;                               //##(0)循环显示
             }
             break;
//##(0)异常状态兜底复位（防跑飞）
        default: 
             CM_StateMachine = 0u;  
             status = true; 
             break;   
    }
//##(0)返回状态
    return(status);
}
                 
/*###############################################################################################################################
# 函数名 :  bool StaticMode(uint8_t LEDS,colorHSL Start, colorHSL End)                                                          #
# 功  能 :  使用 HSL 色彩模式呈现固定颜色(静态显示模式)                                                                         #
# 参  数 :  LEDS = 需要显示的"LED"位图 ,                                                                                        #     
#           Start = 初始显示颜色  , End : 需要显示的颜色(无效) ，Duration = 显示当前"LED"保持时间                               #    
# 说  明 :  显示完成则返回"1",否则返回"0"                                                                                       #
###############################################################################################################################*/
bool StaticMode(Animation *Anim) {
    static uint16_t timeout;
    colorHSL COL;               //##(0)颜色值缓存
    color rgb;                  //##(0)临时缓存HSL转换后的RGB颜色
    boolean  status = false;    //##(0)函数返回标记，false=动画进行中；true=全部闪烁完成
//##(0)其它模式状态机复位               
    CM_StateMachine = FM_StateMachine = BM_StateMachine = 0u;                              
//##(0)执行显示状态机
    switch(SM_StateMachine) {
        case 0x00:
             copyRegisters(LEDBUFF,FrameRGB);                       //##(0)接着上一帧动画(快速拷贝,比 memcpy()快12/15倍))
             COL.H = Anim->StartH;                                  //##(0)起始色度 
             COL.S = Anim->StartS;                                  //##(0)起始饱和度
             COL.L = Anim->StartL;                                  //##(0)起始亮度
             COL.A = 100;
             rgb = HSL_TO_RGBA(COL.H, COL.S, COL.L, COL.A);         //##(0)转换为可直接驱动LED的RGB三基色
             LED_SET_COLOR(Anim->LEDS,rgb,LEDBUFF);                 //##(0)根据LED掩码，给指定LED缓冲区填充当前渐变亮度  
             DisplayFrameRGB((uint32_t *)LEDBUFF);                  //##(0)驱动显示
             copyRegisters(FrameRGB,LEDBUFF);                       //##(0)保存当前帧动画数据(RGB数据)
             timeout = regs.system5ms;                              //##(0)记录当前系统计时，作为下一阶段延时起点
             SM_StateMachine = 0x01;                                //##(0)指向保持时间
             break;
        case 0x01:                                                  //##(0)持续显示"Duration"时间
             uint16_t duration = SWAP_U16(Anim->Duration);          //##(0)渐变时长【由于大小端原因,需要高低字节交换】  
             if(regs.system5ms-timeout<duration/5) break;			//##(0)显示持续时间 
             COL.H = Anim->EndingH;                                 //##(0)结束色度 
             COL.S = Anim->EndingS;                                 //##(0)结束饱和度
             COL.L = Anim->EndingL;                                 //##(0)结束亮度
             COL.A = 100;
             rgb = HSL_TO_RGBA(COL.H, COL.S, COL.L, COL.A);         //##(0)结束色转换为可驱动的三基色数据
             LED_SET_COLOR(Anim->LEDS,rgb,LEDBUFF);                 //##(0)根据LED掩码，给指定LED缓冲区填充当前渐变亮度
             DisplayFrameRGB((uint32_t *)LEDBUFF);                  //##(0)驱动显示
             copyRegisters(FrameRGB,LEDBUFF);                       //##(0)保存当前帧动画数据(RGB数据)
             SM_StateMachine = 0u;                                  //##(0)复位状态机
             timeout = regs.system5ms;
             status = true;                                         //##(0)执行完成
             break;    
//##(0)异常状态兜底复位（防跑飞）
        default: 
             SM_StateMachine = 0u; 
             status = true;
             break;   
    }
    return(status);                                                     //##(0)返回指向状态
}

/*###############################################################################################################################
# 函数名 :  bool FadeMode(uint8_t LEDS,colorHSL Start, colorHSL End)                                                            #
# 功  能 :  渐变模式 ,在两种 HSL 颜色之间随时间渐变(亮度渐变)                                                                   #
# 参  数 :  LEDS = 需要显示的"LED"位图 ,                                                                                        #     
#           Start = 初始显示颜色  , End : 需要显示的颜色 ，Duration = 显示当前"LED"保持时间                                     #    
# 说  明 :  显示完成则返回"1",否则返回"0"                                                                                       #
###############################################################################################################################*/
bool FadeMode(Animation *Anim) {
    static uint16_t timeout;                    //##(0)时间戳，保存每个阶段起始的system5ms计时值，用于延时判断
    static uint16_t FadeStep;                   //##(0)当前渐变帧步进，记录渐变走到第几帧
    static  int8_t  FadeRng;                    //##(0)渐变范围(淡入淡出)
    static colorHSL COL;                        //##(0)颜色值缓存
    static boolean  FadeForward;                //##(0)渐变方向标志：true暗→亮；false亮→暗
    static uint16_t MAX_FRAME = 0u;             //##(0)单向渐变总帧数，由渐变时长Duration计算得出
              color rgb;                        //##(0)临时缓存HSL转换后的RGB颜色
           uint32_t ratio;                      //##(0)比例,进度系数
            boolean status = false;             //##(0)函数返回标记，false=动画进行中；true=全部闪烁完成    
//##(0)其它模式状态机复位               
    CM_StateMachine = SM_StateMachine = BM_StateMachine = 0u;              
//##(0)执行动画主状态机
    switch(FM_StateMachine) {
//##(0)状态0:动画初始化入口,首次启动/一轮全部跑完都会进这里重置参数  
        case 0x00:
             FadeRng = abs((int16_t)Anim->StartL-Anim->EndingL);    //##(0)计算出渐变跨度范围 
             if(FadeRng>100) { status = true; break; }              //##(0)如果范围超过100则认为是溢出直接返回 
             MAX_FRAME = SWAP_U16(Anim->Duration)/5U;           //##(0)渐变过程需要的帧数,防除零
             MAX_FRAME = (MAX_FRAME==0U)? 1U:MAX_FRAME;         //##(0)防除零
             FadeStep = 0U;                                     //##(0)渐变步进计数器清零
             FM_StateMachine = 0x01;                            //##(0)状态机指向下一步(渐变动作) 
             timeout = regs.system5ms;                          //##(0)记录当前系统计时，作为下一阶段延时起点
             COL.A = 100;                                       //##(0)透明度
             if(Anim->StartL > Anim->EndingL) {                 //##(0)如果起始亮度大于结束亮度则为:亮→暗
                COL.H = Anim->StartH;                           
                COL.S = Anim->StartS;                           //##(0)色度/饱和度/亮度为亮度最大的色值                    
                FadeForward = TRUE;                             //##(0)反向调节
             }else{                                             //##(0) 
                COL.H = Anim->EndingH;                          
                COL.S = Anim->EndingS;                          //##(0)色度/饱和度为亮度最大的色值              
                FadeForward = FALSE;                            //##(0)正向调节
             }
             break;
//##(1)状态1:亮度渐变渲染阶段，控制每5ms刷新一帧渐变画面  
        case 0x01:
             copyRegisters(LEDBUFF,FrameRGB);                   //##(1)接着上一帧动画   
             ratio = ((uint32_t)FadeStep*1000U)/MAX_FRAME;      //##(1)仅亮度"L"渐变,H/S/A固定Start不变
             ratio = FadeRng * ratio / 1000U;                   //##(1)计算出调节量步进的渐变亮度值
            (FadeForward==false)?
            (COL.L = Anim->StartL + ratio):                     //##(1)暗→亮；递增
            (COL.L = Anim->StartL - ratio);                     //##(1)亮→暗；递减
             rgb = HSL_TO_RGBA(COL.H, COL.S, COL.L, COL.A);     //##(1)HSL颜色转换成硬件驱动需要的RGB格式
             LED_SET_COLOR(Anim->LEDS, rgb, LEDBUFF);           //##(1)根据LED掩码，给指定LED缓冲区填充当前渐变亮度 
             DisplayFrameRGB((uint32_t *)LEDBUFF);              //##(1)将LED缓冲区数据输出到硬件,点亮LED 
             if(FadeStep++ >= MAX_FRAME) {                      //##(1)检查是否完成单向渐变 ?
                FadeStep = 0U; FM_StateMachine = 0x02;          //##(1)完整渐变则状态机指向下一步
                copyRegisters(FrameRGB,LEDBUFF);                //##(0)保存最后显示的状态
             }
             timeout = regs.system5ms;                          //##(0)记录当前系统计时，作为下一阶段延时起点
             break;
//##(2)状态2 : 结束
        case 0x02: 
             FM_StateMachine = 0U;
             status = true;                                     //##(0)执行完成 
             break;        
        default:     
             FM_StateMachine = 0U;
             status = true;                                     //##(0)执行完成 
             break;        
    }
    return(status);
}
/*###############################################################################################################################
# 函数名 :  bool FadeMode(uint8_t LEDS,colorHSL Start, colorHSL End)                                                            #
# 功  能 :  渐变模式 ,在两种 HSL 颜色之间随时间渐变                                                                             #
# 参  数 :  LEDS = 需要显示的"LED"位图 ,                                                                                        #     
#           Start = 初始显示颜色  , End : 需要显示的颜色 ，Duration = 显示当前"LED"保持时间                                     #  
#           Duration = 渐变所耗时长                                                                                             #
#           Parameter1 = 亮度调节到目标保持时长  Parameter2 = 熄灭时长  count = 闪烁次数                                        #  
# 说  明 :  显示完成则返回"1",否则返回"0"（需要有呼吸模式）                                                                     #
###############################################################################################################################*/
bool BlinkMode(Animation *Anim) {
    static uint16_t timeout;                    //##(0)时间戳，保存每个阶段起始的system5ms计时值，用于延时判断
    static uint16_t FadeStep;                   //##(0)当前渐变帧步进，记录渐变走到第几帧
    static uint8_t  BlinkCount;                 //##(0)完整呼吸周期计数器，一轮明暗算1次,0 = 无限循环
    static  int8_t  FadeRng;                    //##(0)渐变范围(淡入淡出) 
    static boolean  FadeForward;                //##(0)渐变方向标志：true暗→亮；false亮→暗
    static colorHSL COL;                        //##(0)颜色值缓存
    static uint16_t BrightDur,DarkDur;          //##(0)TickBright = 高亮保持节拍(Parameter1), TickDark = 低亮熄灭保持节拍(Parameter2)
    static uint16_t MAX_FRAME = 0u;             //##(0)单向渐变总帧数，由渐变时长Duration计算得出
    static color rgb;                           //##(0)临时缓存HSL转换后的RGB颜色
           uint32_t ratio;                      //##(0)比例,进度系数
           boolean  status = false;             //##(0)函数返回标记，false=动画进行中；true=全部闪烁完成
           uint16_t HoldDelay;      
//##(0)复位其他动画状态机
    CM_StateMachine = SM_StateMachine = FM_StateMachine = 0U;    
//##(3)执行呼吸动画主状态机
    switch(BM_StateMachine) {
//##(0)状态0:动画初始化入口,首次启动/一轮全部跑完都会进这里重置参数        
        case 0x00:                                              
             Anim->Duration = SWAP_U16(Anim->Duration);         //##(0)渐变时长【由于大小端原因,需要高低字节交换】             
             Anim->Parameter1 = SWAP_U16(Anim->Parameter1);     //##(0)亮度最高保持时长
             Anim->Parameter2 = SWAP_U16(Anim->Parameter2);     //##(0)亮度最低保持时长
             FadeRng = abs((int16_t)Anim->StartL-Anim->EndingL);   //##(0)计算出渐变跨度范围  
             if(FadeRng>100) {status = true; break;}            //##(0)如果范围超过100则认为是溢出直接返回            
             BrightDur = Anim->Parameter1/5U;                   //##(0)亮保持时长
               DarkDur = Anim->Parameter2/5U;                   //##(0)关保持时长
             MAX_FRAME = Anim->Duration  /5U;                   //##(0)渐变过程需要的帧数,防除零
             MAX_FRAME = (MAX_FRAME==0U)? 1U:MAX_FRAME;         //##(0)防除零
              FadeStep = BlinkCount = 0U;                       //##(0)闪烁(渐变)周期计数器/渐变步进清零
             BM_StateMachine = 0x01;                            //##(0)状态机指向下一步(渐变动作) 
             if(Anim->StartL > Anim->EndingL) {                 //##(0)采用亮度最高的的色度/饱和度
                COL.H = Anim->StartH;  COL.S = Anim->StartS;    //##(0)起始色的色度/饱和度
                FadeForward = false;                            //##(0)起始亮度大于结束亮度则为正向渐变:亮变暗
             }else{
                COL.H = Anim->EndingH; COL.S = Anim->EndingS;   //##(0)结束色的色度/饱和度 
                FadeForward = true;                             //##(0)结束亮度大于起始亮度则为反向渐变:暗变亮
             }
             timeout = regs.system5ms;                          //##(0)记录当前系统计时，作为下一阶段延时起点
             break;
//##(1)状态1:亮度渐变渲染阶段，控制每5ms刷新一帧渐变画面             
        case 0x01:
             copyRegisters(LEDBUFF,FrameRGB);                   //##(1)接着上一帧动画             
             ratio = ((uint32_t)FadeStep*1000U)/MAX_FRAME;      //##(1)仅亮度"L"渐变,H/S/A固定Start不变
             ratio = FadeRng * ratio / 1000U;                   //##(1)计算出调节量步进的渐变亮度值
            (FadeForward==false)?
            (COL.L = Anim->StartL - ratio):                     //##(1) Anim->StartL > Anim->EndingL ,由暗到亮渐变  
            (COL.L = Anim->StartL + ratio);                     //##(1) Anim->EndingL > Anim->StartL ,由亮到暗渐变
             rgb = HSL_TO_RGBA(COL.H, COL.S, COL.L, COL.A);     //##(1)HSL颜色转换成硬件驱动需要的RGB格式
             LED_SET_COLOR(Anim->LEDS, rgb, LEDBUFF);           //##(1)根据LED掩码，给指定LED缓冲区填充当前渐变亮度   
             DisplayFrameRGB((uint32_t *)LEDBUFF);              //##(1)将LED缓冲区数据输出到硬件，点亮LED
             if(FadeStep++ >= MAX_FRAME) {                      //##(1)检查是否完成单向渐变 ?
                FadeStep = 0U; BM_StateMachine = 0x02;          //##(1)完成单向渐变,渐变步进清零/切换到纯色保持延时状态
             }
             timeout = regs.system5ms;                          //##(0)记录当前系统计时，作为下一阶段延时起点
             break;
//##(2)状态2 : 纯色保持延时阶段，区分高亮/暗态两套保持时长             
        case 0x02:                                              
             HoldDelay = (FadeForward)?  BrightDur:DarkDur;     //##(2)
             if((regs.system5ms-timeout)<HoldDelay) break;      //##(2)未到熄灭保持时间，等待下一轮
             timeout = regs.system5ms;                          //##(2)保持时长满足，刷新时间戳，准备反向渐变
             FadeForward = !FadeForward;                        //##(2)切换渐变方向
             Anim->StartL = FadeForward? 0U:FadeRng;            //##(2)重新配置初始值
             BM_StateMachine = 0x01;                            //##(2)回到渐变状态
             if(FadeForward == false) break;                    //##(2)一个显示周期没有完成则返回
             if(Anim->RepeatCount<=0) break;                    //##(0)一个周期完成则判断是否是一直循环 ?        
             if(++BlinkCount>=Anim->RepeatCount) {              //##(2))
                BM_StateMachine = 0x00; status = TRUE;          //##(0)状态机复位，动画结束
             }
             break;
//##(0)异常状态兜底复位（防跑飞）
        default: 
             BM_StateMachine = 0u; status = true; 
             break;                  
    }
    return(status);      
}
/*###############################################################################################################################
# 函数名 :  void AnimationDisplay_Process(void)                                                                                 #
# 功  能 :  动画显示进程                                                                                                        #
# 参  数 :  NONE                                                                                                                #
###############################################################################################################################*/
void AnimationDisplay_Process(Animation *pAnim) {
    static uint8_t StateMachine;
               bool state = false;
//##(0)如果没有动画显示使能,或者动画显示完成则清除显示动画帧(5帧)数组并返回 
    if(regs.flags.AnimEn == false) {
        memset(pAnim,0u,sizeof(Frame));             //##(0)全部帧动画数组清零(最多五帧动画)
        memset(FrameRGB,0u,sizeof(FrameRGB));       //##(0)最一帧动画数组清零
        StateMachine = regs.chain = 0;              //##(0)复位状态机和帧编号
        CM_StateMachine = SM_StateMachine = 0U;     //##(0)复位动画状态机 
        BM_StateMachine = FM_StateMachine = 0U;     //##(0)复位动画状态机 
        return; 
    }
//##(0)指向显示模式【静态(STATIC)/渐变(FADE)/追逐(CHASER)/闪烁(BLINK)】			   
    StateMachine = pAnim[regs.chain].mode;               
//##(0)有动画显示则按照显示步骤执行状态机器
    switch(StateMachine) {
        case STATE_NONE:                                     
             resetRGBLED();                             //##(0)先复位RGBLED
             regs.flags.AnimEn = false;                 //##(0)如果显示模式是"0"则表明显示完成本组动画全部帧,清除显示动画使能标志      
             break; 
        case STATICM: 
             state = StaticMode(&pAnim[regs.chain]);    //##(0)静态显示模式     
             break;
        case FADEM:
             state = FadeMode(&pAnim[regs.chain]);      //##(0)渐变显示模式 
             break;
        case CHASERM: 
             state = ChaserMode(&pAnim[regs.chain]);    //##(0)跑马灯显示模式 
             break;
        case BLINKM:
             state = BlinkMode(&pAnim[regs.chain]);     //##(0)闪烁显示模式
             break;         
        default:                
             regs.flags.AnimEn = false;                 //##(0)异常状态关闭显示（防跑飞） 
             return;
    }
//##(0)判断单帧是否完成 ? 显示完成重新复位状态机,继续显示下一帧动画
    if(state) { 
        if(regs.chain<5u) { regs.chain++; }             //##(0)在5帧范围内则接着下一帧动画             
        else              { regs.flags.AnimEn = 0; }    //##(0)大于5帧动画则直接结束动画
    }
}

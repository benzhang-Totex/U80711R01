#define FIXED_SHIFT          6U                                                 //##(0)小数位：6位（1.0 = 64 = 1<<6）
#define FIXED_1             (1U << FIXED_SHIFT)                                 //##(0)代表 1.0（64）
#define FIXED_1_6           (FIXED_1 / 6U)                                      //##(0)代表 1/6 ≈ 10
#define FIXED_1_2           (FIXED_1 / 2U)                                      //##(0)代表 1/2 = 32
#define FIXED_2_3           ((FIXED_1 * 2U) / 3U)                               //##(0)代表 2/3 ≈ 42
#define UINT8_TO_FIXED(x)   ((int32_t)(x) * FIXED_1 / 255U)                     //##(0)0~255 → 0~FIXED_1
#define FIXED_TO_UINT8(x)   ((uint8_t)(((x) * 255U + FIXED_1/2U) / FIXED_1))    //##(0)定点数→0~255（四舍五入） 
#define HueOffset           (255.f/360.f)                                       //##(0)360°转为8位色度(255°)的偏移增益    
#define DIV_CEIL(a, b)      ((a + b - 1) / b)                                   //##(0)辅助宏：除法向上取整
